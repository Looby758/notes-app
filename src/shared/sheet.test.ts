import { describe, expect, it } from 'vitest'
import { parseGsheetFile, sheetsFromApi } from './sheet'

describe('parseGsheetFile', () => {
  it('reads the link Google Drive for desktop writes', () => {
    const text = JSON.stringify({ '': 'WARNING! DO NOT EDIT THIS FILE!', doc_id: '1AbC-d_9', resource_key: '', email: 'me@example.com' })
    expect(parseGsheetFile(text)).toEqual({ id: '1AbC-d_9', resourceKey: undefined, email: 'me@example.com' })
  })
  it('reads older links by resource id or url', () => {
    expect(parseGsheetFile(JSON.stringify({ resource_id: 'spreadsheet:XyZ' }))?.id).toBe('XyZ')
    expect(parseGsheetFile(JSON.stringify({ url: 'https://docs.google.com/spreadsheets/d/Q1w2/edit?usp=drivesdk', resource_key: 'k' }))).toEqual({
      id: 'Q1w2',
      resourceKey: 'k',
      email: undefined
    })
  })
  it('refuses anything else', () => {
    expect(parseGsheetFile('not json')).toBeNull()
    expect(parseGsheetFile(JSON.stringify({ doc_id: '../../etc' }))).toBeNull()
    expect(parseGsheetFile(JSON.stringify({}))).toBeNull()
  })
})

describe('sheetsFromApi', () => {
  it('uses Google’s formatted values, skips chart sheets, and trims empty edges', () => {
    const sheets = sheetsFromApi({
      sheets: [
        {
          properties: { title: 'Budget' },
          data: [
            {
              rowData: [
                { values: [{ formattedValue: 'Item' }, { formattedValue: 'Cost' }] },
                { values: [{ formattedValue: 'Rent' }, { formattedValue: '£1,250.00', effectiveValue: { numberValue: 1250 } }, {}] },
                {}
              ],
              columnMetadata: [{ pixelSize: 160 }, { pixelSize: 100 }]
            }
          ]
        },
        { properties: { title: 'Chart', sheetType: 'OBJECT' } },
        { properties: { title: 'Old', hidden: true }, data: [{ startRow: 1, startColumn: 1, rowData: [{ values: [{ formattedValue: 'x' }] }] }] }
      ]
    })
    expect(sheets.map((s) => s.name)).toEqual(['Budget', 'Old'])
    expect(sheets[0].rows).toEqual([
      [{ text: 'Item', num: false }, { text: 'Cost', num: false }],
      [{ text: 'Rent', num: false }, { text: '£1,250.00', num: true }]
    ])
    expect(sheets[0].cols).toBe(2)
    expect(sheets[0].widths).toEqual([20])
    expect(sheets[1].hidden).toBe(true)
    expect(sheets[1].rows).toEqual([[], [{ text: '' }, { text: 'x', num: false }]])
  })
})
